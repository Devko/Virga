// Usage: node packages/rules/src/cli.ts build|check
//   build  compiles rules/, runs all fixtures and writes the generated modules
//   check  does the same but fails if the generated modules are out of date
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { compileRules } from "./compile.ts";

const mode = process.argv[2];
if (mode !== "build" && mode !== "check") {
  console.error("usage: cli.ts build|check");
  process.exit(2);
}

const rulesDir = fileURLToPath(new URL("../../../rules/", import.meta.url));
const { rules, fixtures, errors } = await compileRules(rulesDir);

if (errors.length > 0) {
  for (const error of errors) console.error(`error: ${error}`);
  process.exit(1);
}

const header = "// Generated by `pnpm rules:build` from rules/. Do not edit.\n";
const outputs = {
  "rules.gen.ts": `${header}import type { CompiledRule } from "./types.ts";\n\nexport const RULES: readonly CompiledRule[] = ${JSON.stringify(rules, null, 2)};\n`,
  "fixtures.gen.ts": `${header}import type { RuleFixture } from "./types.ts";\n\nexport const FIXTURES: readonly RuleFixture[] = ${JSON.stringify(fixtures, null, 2)};\n`,
};

let stale = false;
for (const [file, content] of Object.entries(outputs)) {
  const path = fileURLToPath(new URL(file, import.meta.url));
  let current = "";
  try {
    current = readFileSync(path, "utf8");
  } catch {}
  if (current === content) continue;
  if (mode === "check") {
    console.error(`error: ${file} is out of date; run pnpm rules:build`);
    stale = true;
  } else {
    writeFileSync(path, content);
  }
}
if (stale) process.exit(1);
console.log(`${rules.length} rule(s), ${fixtures.length} fixture(s) passed`);
