// Node only. Compiles rules/ and compares the result with the generated
// modules, which the core Worker bundles. Used by cli.ts (rules:build and
// rules:check) and by scripts/deploy.ts, which refuses to deploy rules that
// are not the compiler's output (R8-05).
import { readFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { compileRules } from "./compile.ts";

/** The generated modules, in the order cli.ts reports them. */
export const GENERATED_FILES = ["rules.gen.ts", "fixtures.gen.ts"] as const;

export interface GenerateDirs {
  /** The rule directories, `rules/` at the repository root. */
  rulesDir: string;
  /** Where the generated modules are, `packages/rules/src`. */
  outDir: string;
}

/** This checkout's rules/ and packages/rules/src. */
export const DEFAULT_DIRS: GenerateDirs = {
  rulesDir: fileURLToPath(new URL("../../../rules/", import.meta.url)),
  outDir: fileURLToPath(new URL(".", import.meta.url)),
};

export interface GeneratedFile {
  name: (typeof GENERATED_FILES)[number];
  path: string;
  /** What the compiler makes of rules/. */
  content: string;
  /** The file is missing, or its bytes are not `content` in UTF-8. */
  stale: boolean;
}

export interface GeneratedCheck {
  /** Rules and fixtures that fail the compiler. With any, nothing is compared. */
  errors: string[];
  /** Each generated module, compared with the compiler output; empty when there are errors. */
  files: GeneratedFile[];
  rules: number;
  fixtures: number;
}

const HEADER = "// Generated by `pnpm rules:build` from rules/. Do not edit.\n";

/**
 * Compiles every rule in `rulesDir`, runs its fixtures, and compares the
 * generated modules in `outDir` with the output byte for byte. Writes nothing.
 */
export async function checkGenerated(dirs: GenerateDirs = DEFAULT_DIRS): Promise<GeneratedCheck> {
  const { rules, fixtures, errors } = await compileRules(dirs.rulesDir);
  const counts = { rules: rules.length, fixtures: fixtures.length };
  if (errors.length > 0) return { errors, files: [], ...counts };
  const outputs: Record<GeneratedFile["name"], string> = {
    "rules.gen.ts": `${HEADER}import type { CompiledRule } from "./types.ts";\n\nexport const RULES: readonly CompiledRule[] = ${JSON.stringify(rules, null, 2)};\n`,
    "fixtures.gen.ts": `${HEADER}import type { RuleFixture } from "./types.ts";\n\nexport const FIXTURES: readonly RuleFixture[] = ${JSON.stringify(fixtures, null, 2)};\n`,
  };
  const files = GENERATED_FILES.map((name): GeneratedFile => {
    const path = join(dirs.outDir, name);
    const content = outputs[name];
    let current: Buffer | null = null;
    try {
      current = readFileSync(path);
    } catch {}
    return {
      name,
      path,
      content,
      stale: current === null || !current.equals(Buffer.from(content)),
    };
  });
  return { errors: [], files, ...counts };
}
